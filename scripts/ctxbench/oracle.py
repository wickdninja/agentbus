"""Independent ctxbench oracle, derived only from ctxbench-protocol.md D1-D8.

Events are (ISO-8601 UTC time, actor, action, fields) tuples. Messages use
action='post' and kind/to/body/topic/reply_to fields; claims use res and an
optional frm for takeover. Broadcast recipients are '*'. Message ids start at
1 and include the alert generated by each takeover (Histories/Takeover expansion).

Pass the checkpoint's event prefix, in list order. P2 inputs={'x': path};
P6 inputs={'y': item}; other probes need no inputs. Answers are sets, except
P5's (id, subject) pair and P7's (P1, P3, P4) triple of sets. No CLI, renderer,
registered parser, filesystem, or wall clock is consulted.
"""

from dataclasses import dataclass, field
from datetime import datetime, timedelta
from typing import Any, Dict, Iterable, Mapping, Optional, Set, Tuple


Event = Tuple[str, str, str, Mapping[str, Any]]


def _time(value: str) -> datetime:
    """Read the semantic history's timestamp, including on Python 3.9."""
    return datetime.fromisoformat(value.replace("Z", "+00:00"))


def _overlap(left: str, right: str) -> bool:
    """D6: equality or containment at a path-component boundary, symmetrically."""
    left, right = left.rstrip("/"), right.rstrip("/")
    return (left == right or left.startswith(right + "/")
            or right.startswith(left + "/"))


@dataclass
class _State:
    roster: Set[str] = field(default_factory=set)
    joined: Set[str] = field(default_factory=set)
    left: Dict[str, datetime] = field(default_factory=dict)
    messages: Dict[int, Tuple[datetime, str, Mapping[str, Any]]] = field(default_factory=dict)
    todo_closers: Set[int] = field(default_factory=set)
    question_closers: Set[int] = field(default_factory=set)
    claims: Dict[str, Tuple[str, datetime]] = field(default_factory=dict)


def _fold(events: Iterable[Event]) -> _State:
    state = _State()
    message_id = 0
    for timestamp, actor, action, fields in events:
        when = _time(timestamp)
        if action == "join":
            # D1: rejoining restores membership; a crash never removes it.
            state.roster.add(actor)
            state.joined.add(actor)
        elif action == "leave":
            # D1, D7: remember the leave even if a later join restores membership.
            state.roster.discard(actor)
            state.left[actor] = when.replace(microsecond=0)
            # D5: leaving ends every claim held by this actor.
            state.claims = {res: claim for res, claim in state.claims.items()
                            if claim[0] != actor}
        elif action == "claim":
            # D5: a claim, renewal, or takeover starts a fresh 120-minute TTL.
            # Replacing the resource's holder ends the previous holder's claim.
            state.claims[fields["res"]] = (actor, when + timedelta(minutes=120))
            if fields.get("frm") is not None:
                # The synthetic takeover alert consumes a message id too.
                message_id += 1
        elif action == "release":
            # D5: release ends this holder's claim, not another holder's claim.
            resource = fields["res"]
            claim = state.claims.get(resource)
            if claim is not None and claim[0] == actor:
                del state.claims[resource]
        elif action == "post":
            message_id += 1
            state.messages[message_id] = (when, actor, fields)
            target = fields.get("reply_to")
            # D3: only a direct done/dropped reply closes a todo.
            if target is not None and fields["kind"] in {"done", "dropped"}:
                state.todo_closers.add(target)
            # D4: only a direct answer closes a question.
            if target is not None and fields["kind"] == "answer":
                state.question_closers.add(target)
        elif action in {"goal", "fact", "inbox", "crash"}:
            # D1, D3-D5: these do not change roster, closure, or claim lifetime.
            # Crashes normally have no event; an explicit marker is harmless.
            continue
        else:
            raise ValueError("Unknown semantic event action: " + action)
    return state


def _owner(sender: str, message: Mapping[str, Any]) -> str:
    """D2: a broadcast todo belongs to its sender."""
    return sender if message["to"] == "*" else message["to"]


def _answer(state: _State, probe: str, me: str, now: datetime,
            inputs: Mapping[str, Any]) -> Any:
    # D3: unrelated replies, reading, leaves, and expiry never close todos.
    todos = {mid: row for mid, row in state.messages.items()
             if row[2]["kind"] == "todo" and mid not in state.todo_closers}

    if probe == "P1":
        # D2, D3: ownership and openness are independent of roster membership.
        return {mid for mid, (_, sender, msg) in todos.items()
                if _owner(sender, msg) == me}
    if probe == "P3":
        # D4 and P3: include broadcasts, exclude my own questions.
        return {mid for mid, (_, sender, msg) in state.messages.items()
                if msg["kind"] == "question" and mid not in state.question_closers
                and msg["to"] in {me, "*"} and sender != me}
    if probe == "P4":
        result = set()
        for mid, (when, sender, msg) in todos.items():
            owner = _owner(sender, msg)
            # AMBIGUITY: D7's final roster exclusion is read as applying to other
            # owners; its explicit 'owner is me' clause takes precedence.
            # D1, D2, D3, D7: a former owner's leave must be at/after todo time,
            # compared in whole seconds, and the owner must still be absent.
            if owner == me or (owner not in state.roster and owner in state.joined
                               and owner in state.left
                               and state.left[owner] >= when.replace(microsecond=0)):
                result.add(mid)
        return result
    if probe == "P5":
        # D8: both kind and topic must be decision; choose the largest id.
        decisions = [(mid, msg) for mid, (_, _, msg) in state.messages.items()
                     if msg["kind"] == "decision" and msg.get("topic") == "decision"]
        if not decisions:
            # AMBIGUITY: the task also says 'or None'; the protocol probe table
            # explicitly specifies (null, null), so return (None, None).
            return (None, None)
        mid, msg = max(decisions, key=lambda row: row[0])
        last_line = msg["body"].splitlines()[-1]
        if not last_line.startswith("Subject: "):
            raise ValueError("D8 decision lacks the benchmark's final Subject: footer")
        return (mid, last_line[len("Subject: "):])
    if probe in {"P2", "P6"}:
        path = inputs["x"] if probe == "P2" else "src/" + inputs["y"] + "/"
        # D5, D6: expiry is strictly later than now, regardless of roster status.
        holders = {holder for res, (holder, expiry) in state.claims.items()
                   if expiry > now and _overlap(res, path)}
        if probe == "P6":
            # D1-D3 and P6: union claim holders with rostered open-todo owners.
            holders.update(_owner(sender, msg) for _, sender, msg in todos.values()
                           if msg.get("topic") == inputs["y"]
                           and _owner(sender, msg) in state.roster)
        return holders
    if probe == "P7":
        return tuple(_answer(state, part, me, now, inputs) for part in ("P1", "P3", "P4"))
    raise ValueError("Unknown ctxbench probe: " + probe)


def oracle(events: Iterable[Event], probe: str, me: str, now: str,
           inputs: Optional[Mapping[str, Any]] = None) -> Any:
    """Return the exact P1-P6 answer, or one P7 refresh, without side effects.

    AMBIGUITY: 'at a given time' does not identify a list position when several
    events share a second. Per Checkpoints and P7 construction, events is the
    supplied checkpoint prefix, folded in list order, not a history filtered by
    now. The caller chooses that prefix; now determines D5 expiry only.
    """
    return _answer(_fold(events), probe, me, _time(now), inputs or {})


def p7(events: Iterable[Event], me: str, now: str) -> Tuple[Set[int], Set[int], Set[int]]:
    """D1-D4, D7: return (P1, P3, P4) for one caller-selected refresh prefix."""
    return oracle(events, "P7", me, now, {})
