#!/usr/bin/env python3
"""Rewrite the embedded skill block in bin/agentbus from skills/agentbus/SKILL.md.

    python3 scripts/embed_skill.py            rewrite the block between # BEGIN EMBEDDED SKILL and # END EMBEDDED SKILL
    python3 scripts/embed_skill.py --check    exit 1 unless the block is what a rewrite would produce
    python3 scripts/embed_skill.py --release  also record the current SKILL.md hash as released (release prep only)

The block holds SKILL_TEXT (what `agentbus skill` prints and `agentbus setup claude` installs),
AGENTS_SNIPPET (the Codex AGENTS.md block body) and SKILL_SHA256_HISTORY (the sha256 of every released
SKILL.md; `setup` treats an installed file with a listed hash as unedited) and AGENTS_SHA256_HISTORY (the
same for the AGENTS.md block body). Only the brain runs this, at
merge; branches edit SKILL.md and keep the byte budget (tests/test_skill.sh).
"""
import argparse
import hashlib
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BIN = os.path.join(ROOT, "bin", "agentbus")
SKILL = os.path.join(ROOT, "skills", "agentbus", "SKILL.md")
BEGIN = "# BEGIN EMBEDDED SKILL (generated by scripts/embed_skill.py; edit skills/agentbus/SKILL.md, not this block)"
END = "# END EMBEDDED SKILL"
SKILL_CAP = 4800
SNIPPET_CAP = 700
# sha256 of skill/SKILL.md at v0.1.0, the first released skill.
SEED_HISTORY = ["2af5e4efedd84d7da42da6c4c5ddd02f230cc002e05b733741557dfd38b06156"]

# The Codex AGENTS.md block body. It names the bus copy, per the version policy.
AGENTS_SNIPPET = (
    "## agentbus\n"
    "This workspace has a shared agentbus. Run `.agentbus/bin/agentbus skill` for the full protocol; if it says "
    "`unknown command 'skill'`, the copy is 0.1.x: stop and tell the user to run `agentbus upgrade --all PARENT_DIR`.\n"
    "Join: `.agentbus/bin/agentbus --as NAME join`. "
    "Before editing: `.agentbus/bin/agentbus --as NAME claim PATH --purpose WHY`.\n"
    "Between steps: `.agentbus/bin/agentbus --as NAME inbox --limit 20`. "
    "Finish: `.agentbus/bin/agentbus --as NAME post RESULT --kind done`, then `leave`.\n"
)


def literal(name, text):
    lines = text.splitlines(keepends=True)
    body = "".join(f"    {line!r}\n" for line in lines)
    return f"{name} = (\n{body})\n"


def history_literal(name, history):
    hashes = "".join(f'    "{h}",\n' for h in history)
    return f"{name} = (\n{hashes})\n"


def block(skill_text, history, agents_history):
    return (BEGIN + "\n" + literal("SKILL_TEXT", skill_text) + literal("AGENTS_SNIPPET", AGENTS_SNIPPET)
            + history_literal("SKILL_SHA256_HISTORY", history)
            + history_literal("AGENTS_SHA256_HISTORY", agents_history) + END + "\n")


def split_bin(src):
    m = re.search(r"^" + re.escape("# BEGIN EMBEDDED SKILL") + r".*\n(.*?)^" + re.escape(END) + r"\n", src, re.S | re.M)
    if not m:
        sys.exit("embed_skill: bin/agentbus has no '# BEGIN EMBEDDED SKILL' ... '# END EMBEDDED SKILL' block")
    return m


def current_history(src, name="SKILL_SHA256_HISTORY", seed=SEED_HISTORY):
    m = split_bin(src)
    if name + " = (" not in m.group(1):
        return list(seed)
    part = m.group(1).split(name + " = (", 1)[1].split("\n)\n", 1)[0]
    return re.findall(r'^    "([0-9a-f]{64})",$', part, re.M) or list(seed)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="exit 1 unless the embedded block is current")
    ap.add_argument("--release", action="store_true", help="record the current SKILL.md hash as released")
    a = ap.parse_args()
    with open(SKILL, encoding="utf-8", newline="") as f:
        skill_text = f.read()
    size = len(skill_text.encode("utf-8"))
    if size > SKILL_CAP:
        sys.exit(f"embed_skill: SKILL.md is {size} bytes, the cap is {SKILL_CAP}")
    if len(AGENTS_SNIPPET.encode("utf-8")) > SNIPPET_CAP:
        sys.exit(f"embed_skill: the AGENTS.md block is over {SNIPPET_CAP} bytes")
    if not skill_text.endswith("<!-- agentbus:managed -->\n"):
        sys.exit("embed_skill: SKILL.md must end with the line <!-- agentbus:managed -->")
    with open(BIN, encoding="utf-8", newline="") as f:
        src = f.read()
    history = current_history(src)
    agents_history = current_history(src, "AGENTS_SHA256_HISTORY", [])
    digest = hashlib.sha256(skill_text.encode("utf-8")).hexdigest()
    agents_digest = hashlib.sha256(AGENTS_SNIPPET.encode("utf-8")).hexdigest()
    if a.release and digest not in history:
        history.append(digest)
    if a.release and agents_digest not in agents_history:
        agents_history.append(agents_digest)
    new = src[:split_bin(src).start()] + block(skill_text, history, agents_history) + src[split_bin(src).end():]
    if a.check:
        if new != src:
            sys.exit("embedded skill is stale: run python3 scripts/embed_skill.py")
        print("embedded skill is current")
        return
    if new != src:
        tmp = BIN + ".embed.tmp"
        with open(tmp, "w", encoding="utf-8", newline="") as f:
            f.write(new)
        os.chmod(tmp, os.stat(BIN).st_mode & 0o7777)
        os.replace(tmp, BIN)
    print(f"embedded skill: {size} bytes, {len(history)} released hash(es)" + ("" if new != src else " (unchanged)"))


if __name__ == "__main__":
    main()
